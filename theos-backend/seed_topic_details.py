def main():
    db = SessionLocal()
    try:
        for name, meta in DETAILS.items():
            ev = db.query(models.Event).filter_by(name=name).first()
            if ev:
                ev.period = meta["period"]
                ev.historical_background = meta["historical_background"]
                print("event*", name)
            else:
                print("event? missing", name)
        for name, info in CHAR_INFO.items():
            ch = db.query(models.Character).filter_by(name=name).first()
            if ch:
                ch.genealogy_info = info
                print("char*", name)
            else:
                print("char? missing", name)
        db.commit()
        print("OK detail enrich")
    finally:
        db.close()


if __name__ == "__main__":
    main()
