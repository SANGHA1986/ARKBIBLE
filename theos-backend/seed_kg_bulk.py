def upsert_doctrine(db: Session, name: str, description: str) -> models.Doctrine:
    row = db.query(models.Doctrine).filter_by(name=name).first()
    if row:
        if description and (not row.description or len(row.description) < 8):
            row.description = description
        return row
    row = models.Doctrine(name=name, description=description)
    db.add(row)
    db.flush()
    return row


def main():
    db = SessionLocal()
    try:
        print("=== seed_kg_bulk ===")
        n_c = n_e = n_l = n_k = n_d = 0

        for name, orig, era, info, refs in CHARACTERS:
            ch = upsert_character(db, name, orig, era, info)
            for book, c, v in refs:
                link_verse(ch, verse_of(db, book, c, v))
            n_c += 1

        for name, period, bg, refs in EVENTS:
            ev = upsert_event(db, name, period, bg)
            for book, c, v in refs:
                link_verse(ev, verse_of(db, book, c, v))
            n_e += 1

        # 사건–인물 연결 (해석에 관련 인물이 보이게)
        event_chars = {
            "예루살렘 공의회": ["베드로", "바울", "바나바", "야고보(주의 형제)"],
            "오순절": ["베드로"],
            "스데반 순교": ["스데반"],
            "바울의 회심": ["바울"],
            "바울의 선교 여행": ["바울", "바나바"],
            "십자가": ["예수", "빌라도"],
            "부활": ["예수", "마리아 막달라"],
            "출애굽": ["모세", "아론"],
        }
        for ev_name, char_names in event_chars.items():
            ev = db.query(models.Event).filter_by(name=ev_name).first()
            if not ev:
                continue
            for cn in char_names:
                ch = db.query(models.Character).filter_by(name=cn).first()
                if ch and ch not in ev.characters:
                    ev.characters.append(ch)

        for name, ancient, refs in LOCATIONS:
            loc = upsert_location(db, name, ancient)
            for book, c, v in refs:
                link_verse(loc, verse_of(db, book, c, v))
            n_l += 1

        for name, definition in CONCEPTS:
            upsert_concept(db, name, definition)
            n_k += 1

        for name, description in DOCTRINES:
            upsert_doctrine(db, name, description)
            n_d += 1

        db.commit()
        print(
            f"upserted characters~{n_c} events~{n_e} locations~{n_l} concepts~{n_k} doctrines~{n_d}"
        )
        print(
            "DB totals:",
            db.query(models.Character).count(),
            db.query(models.Event).count(),
            db.query(models.Location).count(),
            db.query(models.Concept).count(),
            db.query(models.Doctrine).count(),
        )
    finally:
        db.close()


if __name__ == "__main__":
    main()
