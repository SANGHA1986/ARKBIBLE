from __future__ import annotations

from sqlalchemy.orm import Session

import models
from database import SessionLocal


def verse_of(db: Session, book: str, ch: int, vs: int):
    b = db.query(models.BibleBook).filter_by(name=book).first()
    if not b:
        return None
    return (
        db.query(models.Verse)
        .filter_by(book_id=b.id, chapter_num=ch, verse_num=vs)
        .first()
    )


def link_verse(entity, v):
    if v is None:
        return
    if v not in entity.verses:
        entity.verses.append(v)


def upsert_character(db: Session, name, original, era, info) -> models.Character:
    row = db.query(models.Character).filter_by(name=name).first()
    if row:
        if original and not row.original_name:
            row.original_name = original
        if era and not row.era:
            row.era = era
        if info and (not row.genealogy_info or len(row.genealogy_info) < 8):
            row.genealogy_info = info
        return row
    row = models.Character(
        name=name, original_name=original, era=era, genealogy_info=info
    )
    db.add(row)
    db.flush()
    return row


def upsert_event(db: Session, name, period, bg) -> models.Event:
    row = db.query(models.Event).filter_by(name=name).first()
    if row:
        if period and (not row.period or len(row.period) < len(period)):
            row.period = period
        if bg and (not row.historical_background or len(row.historical_background) < len(bg)):
            row.historical_background = bg
        return row
    row = models.Event(name=name, period=period, historical_background=bg)
    db.add(row)
    db.flush()
    return row


def upsert_location(db: Session, name, ancient="") -> models.Location:
    row = db.query(models.Location).filter_by(name=name).first()
    if row:
        if ancient and not row.ancient_name:
            row.ancient_name = ancient
        return row
    row = models.Location(name=name, ancient_name=ancient or None)
    db.add(row)
    db.flush()
    return row


def upsert_concept(db: Session, name, definition) -> models.Concept:
    row = db.query(models.Concept).filter_by(name=name).first()
    if row:
        if definition and (not row.definition or len(row.definition) < 10):
            row.definition = definition
        return row
    row = models.Concept(name=name, definition=definition)
    db.add(row)
    db.flush()
    return row


