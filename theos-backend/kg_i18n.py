def _has_hangul(text: str | None) -> bool:
    return bool(text and re.search(r"[가-힣]", text))


def kg_name(ko_name: str, lang: str, table: dict[str, str]) -> str:
    if _norm_lang(lang) != "EN":
        return ko_name
    return table.get(ko_name, ko_name if not _has_hangul(ko_name) else "[Untranslated name]")


