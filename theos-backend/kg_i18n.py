def era_text(ko: str | None, lang: str = "KO") -> str | None:
    if not ko:
        return ko
    if _norm_lang(lang) != "EN":
        return ko
    if ko in KO_TO_EN_ERA:
        return KO_TO_EN_ERA[ko]
    out = ko
    for k, v in sorted(KO_TO_EN_ERA.items(), key=lambda x: -len(x[0])):
        if k in out:
            out = out.replace(k, v)
    if _has_hangul(out):
        out = re.sub(r"[가-힣]+", " ", out)
        out = re.sub(r"\s{2,}", " ", out).strip(" ·/-")
        return out or "—"
    return out


